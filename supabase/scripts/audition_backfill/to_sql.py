"""Convierte el CSV de relleno (propose.py) en la migración SQL del backfill.

Uso: python3 -I to_sql.py <auditions_backfill.csv> <out.sql>
Las deadlines llevan un UUID determinista (uuid5 de audición + clave) para que
la migración sea reproducible y las fechas puedan referenciarlas sin consultas.
"""
import csv
import sys
import uuid

NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "danza-app:audition_deadlines")

rows = list(csv.DictReader(open(sys.argv[1])))


def lit(value):
    """Literal SQL: '' -> NULL, comillas escapadas."""
    if value is None or value.strip() == "":
        return "null"
    return "'" + value.replace("'", "''") + "'"


def deadline_id(row):
    return str(uuid.uuid5(NAMESPACE, f"{row['audition_id']}:{row['deadline_key']}"))


deadlines = {}
for r in rows:
    deadlines.setdefault((r["audition_id"], r["deadline_key"]), r)

deadline_values = ",\n".join(
    f"  ({lit(deadline_id(r))}, {lit(r['audition_id'])}, {lit(r['deadline_date'])}, "
    f"{lit(r['deadline_date_label'])}, {lit(r['deadline_notes'])})"
    for r in deadlines.values()
)
date_values = ",\n".join(
    f"  ({lit(deadline_id(r))}, {lit(r['start_date'])}, {lit(r['end_date'])}, {lit(r['format'])}, "
    f"{lit(r['place'])}, {lit(r['country_iso_code'])}, {lit(r['date_label'])}, {lit(r['notes'])})"
    for r in rows
)
schedule_labels = {r["audition_id"]: r["schedule_label"] for r in rows if r["schedule_label"].strip()}
schedule_label_sql = ""
if schedule_labels:
    values = ",\n".join(f"  ({lit(aid)}, {lit(label)})" for aid, label in schedule_labels.items())
    schedule_label_sql = f"""
update public.auditions a
   set schedule_label = v.schedule_label
  from (values
{values}
) as v(audition_id, schedule_label)
 where a.id = v.audition_id::uuid;
"""

sql = f"""-- Audition schedule redesign, phase 1 of 3: copy every existing audition into
-- audition_deadlines / audition_dates. See docs/adr/0001-audition-schedule-tree.md.
--
-- GENERATED by supabase/scripts/audition_backfill (propose.py -> validate.py -> to_sql.py)
-- from production data read on 2026-10-12; do not edit by hand, regenerate instead.
-- Rules agreed for rows the old modes could not express:
--   TBA with a fixed deadline       -> audition date = deadline + 30 days
--   no date at all (ASAP + TBA)     -> deadline = created + 30 days, audition = created + 60 days
--   month / period in the TBA note  -> that period (over 60 days: its last 60)
--   date ending before the deadline -> its own deadline on its start date
--   various_dates entries           -> place / notes / ranges parsed from each label
--
-- Rows are joined to existing auditions and skipped once an audition already has
-- deadlines, so on a database without these auditions this is a no-op. The check
-- at the end fails the migration if any audition is left without a schedule (for
-- example one created after the data was read): regenerate and push again.

insert into public.audition_deadlines (id, audition_id, date, date_label, notes)
select v.id::uuid, a.id, v.date::date, v.date_label, v.notes
  from (values
{deadline_values}
) as v(id, audition_id, date, date_label, notes)
  join public.auditions a on a.id = v.audition_id::uuid
 where not exists (select 1 from public.audition_deadlines d where d.audition_id = a.id);

insert into public.audition_dates (
  deadline_id, start_date, end_date, format, place, country_iso_code, date_label, notes
)
select d.id, v.start_date::date, v.end_date::date, v.format::public.audition_date_format,
       v.place, v.country_iso_code, v.date_label, v.notes
  from (values
{date_values}
) as v(deadline_id, start_date, end_date, format, place, country_iso_code, date_label, notes)
  join public.audition_deadlines d on d.id = v.deadline_id::uuid
 where not exists (select 1 from public.audition_dates x where x.deadline_id = d.id);
{schedule_label_sql}
do $$
declare
  v_without_deadline int;
  v_without_dates    int;
  v_late_deadlines   int;
begin
  select count(*) into v_without_deadline
    from public.auditions a
   where not exists (select 1 from public.audition_deadlines d where d.audition_id = a.id);

  select count(*) into v_without_dates
    from public.audition_deadlines d
   where not exists (select 1 from public.audition_dates x where x.deadline_id = d.id);

  select count(*) into v_late_deadlines
    from public.audition_deadlines d
    join public.audition_dates x on x.deadline_id = d.id
   where d.date > x.end_date;

  if v_without_deadline + v_without_dates + v_late_deadlines > 0 then
    raise exception 'audition backfill incomplete: % auditions without deadline, % deadlines without dates, % deadlines after their dates',
      v_without_deadline, v_without_dates, v_late_deadlines;
  end if;
end;
$$;
"""
open(sys.argv[2], "w").write(sql)
print(f"deadlines={len(deadlines)} dates={len(rows)} schedule_labels={len(schedule_labels)}")
